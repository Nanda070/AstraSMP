CREATE TABLE IF NOT EXISTS profiles (
  uuid CHAR(36) PRIMARY KEY,
  name VARCHAR(16) NOT NULL,
  coins BIGINT NOT NULL DEFAULT 0,
  mmr INT NOT NULL DEFAULT 50,
  kills INT NOT NULL DEFAULT 0,
  deaths INT NOT NULL DEFAULT 0,
  sold_value BIGINT NOT NULL DEFAULT 0,
  event_points INT NOT NULL DEFAULT 0,
  faction VARCHAR(32) NOT NULL DEFAULT '',
  base_level INT NOT NULL DEFAULT 1,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  actor_uuid CHAR(36) NULL,
  target_uuid CHAR(36) NULL,
  type VARCHAR(32) NOT NULL,
  amount BIGINT NOT NULL,
  meta TEXT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS auction_lots (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  seller_uuid CHAR(36) NOT NULL,
  item LONGTEXT NOT NULL,
  price BIGINT NOT NULL,
  amount INT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  expires_at BIGINT NOT NULL DEFAULT 0,
  sold TINYINT(1) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS discord_links (
  uuid CHAR(36) PRIMARY KEY,
  discord_id VARCHAR(32) NOT NULL,
  code VARCHAR(12) NULL,
  verified TINYINT(1) NOT NULL DEFAULT 0,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS contracts (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  creator_uuid CHAR(36) NOT NULL,
  target_uuid CHAR(36) NOT NULL,
  reward BIGINT NOT NULL,
  contract_type VARCHAR(32) NOT NULL,
  note TEXT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS factions (
  name VARCHAR(32) PRIMARY KEY,
  owner_uuid CHAR(36) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS faction_members (
  faction_name VARCHAR(32) NOT NULL,
  uuid CHAR(36) NOT NULL,
  role VARCHAR(16) NOT NULL DEFAULT 'MEMBER',
  joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (faction_name, uuid)
);

CREATE TABLE IF NOT EXISTS territory_claims (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  faction_name VARCHAR(32) NOT NULL,
  world VARCHAR(32) NOT NULL,
  chunk_x INT NOT NULL,
  chunk_z INT NOT NULL,
  level INT NOT NULL DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_chunk (world, chunk_x, chunk_z)
);

CREATE TABLE IF NOT EXISTS world_events (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  event_type VARCHAR(32) NOT NULL,
  world VARCHAR(32) NOT NULL,
  x INT NOT NULL,
  y INT NOT NULL,
  z INT NOT NULL,
  started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  finished TINYINT(1) NOT NULL DEFAULT 0
);
